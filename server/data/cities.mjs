let i = 0;
for (const line of CN_RAW.trim().split('\n')) {
  const [name, province, lng, lat, pli, agri] = line.split('|');
  addCity({
    id: `c${i++}`,
    name,
    fullName: province === name ? name : `${province}·${name}`,
    country: '中国',
    province,
    lng: Number(lng),
    lat: Number(lat),
    pli: Number(pli),
    agri: agri ? Number(agri) : 0,
    currency: 'CNY',
    fx: 1,
    scope: 'CN',
  });
}

for (const line of INTL_RAW.trim().split('\n')) {
  const [name, code, lng, lat, adj] = line.split('|');
  const ct = COUNTRIES[code];
  addCity({
    id: `c${i++}`,
    name,
    fullName: `${ct.name}·${name}`,
    country: ct.name,
    countryCode: code,
    province: null,
    lng: Number(lng),
    lat: Number(lat),
    pli: Number((ct.pli * Number(adj || 1)).toFixed(3)),
    agri: 0,
    currency: ct.currency,
    fx: ct.fx,
    scope: 'INTL',
  });
}

